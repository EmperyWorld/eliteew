#!/usr/bin/env python3
"""Site Studio internal custom-domain DNS/TLS outbox controller.

Dry-run prints CoreDNS override candidates for pending `site_studio_domain_dns_outbox`
rows. Apply mode marks selected outbox rows as applied in Postgres so the operator
can keep DB state aligned with the manually reviewed CoreDNS change.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import re
import shutil
import ssl
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

_HOST_RE = re.compile(r"^[a-z0-9](?:[a-z0-9.-]{0,251}[a-z0-9])?$")


def _database_dsn() -> str:
    dsn = os.environ.get("DATABASE_URL") or os.environ.get("POSTGRES_DSN")
    if dsn:
        return dsn
    host = os.environ.get("POSTGRES_HOST", "127.0.0.1")
    port = os.environ.get("POSTGRES_PORT", "5432")
    db = os.environ.get("POSTGRES_DB", "eliteew")
    user = os.environ.get("POSTGRES_USER", "ai_user")
    password = os.environ.get("POSTGRES_PASSWORD", "")
    auth = f"{user}:{password}@" if password else f"{user}@"
    return f"postgresql://{auth}{host}:{port}/{db}"


def _record(row: dict[str, Any]) -> str:
    return f"{str(row['hostname']).rstrip('.')} CNAME {str(row['target_hostname']).rstrip('.')}."


def _validate_hostname(value: str) -> str:
    hostname = value.strip().lower().rstrip(".")
    if not hostname or not _HOST_RE.match(hostname) or ".." in hostname:
        raise ValueError(f"Unsafe hostname in DNS candidate: {value!r}")
    return hostname


def _candidate_text(rows: list[dict[str, Any]]) -> str:
    lines = [
        "; Generated by site-studio-dns-tls-controller.py",
        f"; generated_at={datetime.now(UTC).isoformat()}",
    ]
    for row in rows:
        hostname = _validate_hostname(str(row["hostname"]))
        target = _validate_hostname(str(row["target_hostname"]))
        lines.append(f"{hostname}. 60 IN CNAME {target}.")
    return "\n".join(lines) + "\n"


def _write_candidate(rows: list[dict[str, Any]], path: str) -> None:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(_candidate_text(rows), encoding="utf-8")


def _apply_candidate_file(candidate_path: str, destination_path: str, *, backup: bool) -> Path | None:
    candidate = Path(candidate_path)
    destination = Path(destination_path)
    if not candidate.is_file():
        raise FileNotFoundError(f"Candidate file not found: {candidate}")
    content = candidate.read_text(encoding="utf-8")
    for line in content.splitlines():
        if not line.strip() or line.lstrip().startswith(";"):
            continue
        parts = line.split()
        if len(parts) < 5 or parts[2].upper() != "IN" or parts[3].upper() != "CNAME":
            raise ValueError(f"Unsupported DNS candidate line: {line}")
        _validate_hostname(parts[0].rstrip("."))
        _validate_hostname(parts[4].rstrip("."))
    backup_path: Path | None = None
    if backup and destination.exists():
        stamp = datetime.now(UTC).strftime("%Y%m%d%H%M%S")
        backup_path = destination.with_suffix(f"{destination.suffix}.{stamp}.bak")
        shutil.copy2(destination, backup_path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(content, encoding="utf-8")
    return backup_path


def _inspect_certificate(cert_file: str, hostname: str) -> dict[str, Any]:
    safe_hostname = _validate_hostname(hostname)
    cert = ssl._ssl._test_decode_cert(cert_file)  # noqa: SLF001
    sans = [
        str(value).lower()
        for key, value in cert.get("subjectAltName", [])
        if str(key).lower() == "dns"
    ]
    expires_at_raw = str(cert.get("notAfter") or "")
    expires_at = datetime.fromtimestamp(ssl.cert_time_to_seconds(expires_at_raw), UTC)
    now = datetime.now(UTC)
    days_remaining = int((expires_at - now).total_seconds() // 86400)

    def _matches(pattern: str) -> bool:
        if pattern.startswith("*."):
            return safe_hostname.endswith(pattern[1:]) and safe_hostname.count(".") == pattern.count(".")
        return pattern == safe_hostname

    san_match = any(_matches(pattern) for pattern in sans)
    return {
        "hostname": safe_hostname,
        "cert_file": str(Path(cert_file).resolve()),
        "sans": sans,
        "san_match": san_match,
        "expires_at": expires_at.isoformat(),
        "days_remaining": days_remaining,
        "expiry_warning": days_remaining < 30,
    }


async def _connect():
    try:
        import asyncpg  # type: ignore[import-not-found]
    except Exception as exc:  # noqa: BLE001
        raise RuntimeError("asyncpg is required inside the API image/controller environment") from exc
    return await asyncpg.connect(_database_dsn())


async def _fetch_pending(conn, *, limit: int) -> list[dict[str, Any]]:
    rows = await conn.fetch(
        """
        SELECT o.id, o.binding_id, o.hostname, o.target_hostname, o.status, o.requested_at,
               b.tls_status, b.status AS binding_status
        FROM site_studio_domain_dns_outbox o
        JOIN site_studio_domain_bindings b ON b.id = o.binding_id
        WHERE o.status = 'pending'
        ORDER BY o.requested_at ASC
        LIMIT $1
        """,
        limit,
    )
    return [dict(row) for row in rows]


async def _apply_rows(conn, rows: list[dict[str, Any]], *, actor: str) -> None:
    now = datetime.now(UTC).replace(tzinfo=None)
    async with conn.transaction():
        for row in rows:
            metadata = json.dumps(
                {
                    "applied_by": actor,
                    "applied_by_controller": "site-studio-dns-tls-controller.py",
                    "record": _record(row),
                },
                ensure_ascii=False,
            )
            await conn.execute(
                """
                UPDATE site_studio_domain_dns_outbox
                SET status = 'applied',
                    applied_at = $2,
                    metadata_json = metadata_json || $3::jsonb
                WHERE id = $1
                """,
                row["id"],
                now,
                metadata,
            )
            await conn.execute(
                """
                UPDATE site_studio_domain_bindings
                SET status = CASE WHEN status = 'verified' THEN 'route_pending' ELSE status END,
                    route_ready_at = COALESCE(route_ready_at, $2),
                    metadata_json = metadata_json || $3::jsonb,
                    updated_at = $2
                WHERE id = $1
                """,
                row["binding_id"],
                now,
                metadata,
            )


async def _mark_tls_ready(conn, *, binding_id: str, actor: str, evidence: dict[str, Any]) -> None:
    if not evidence.get("san_match"):
        raise RuntimeError("Refusing TLS ready: certificate SAN does not match hostname")
    if int(evidence.get("days_remaining") or 0) <= 0:
        raise RuntimeError("Refusing TLS ready: certificate is expired")
    now = datetime.now(UTC).replace(tzinfo=None)
    metadata = json.dumps(
        {
            "tls_ready_by": actor,
            "tls_ready_by_controller": "site-studio-dns-tls-controller.py",
            "tls_evidence": evidence,
        },
        ensure_ascii=False,
    )
    await conn.execute(
        """
        UPDATE site_studio_domain_bindings
        SET tls_status = 'ready',
            last_error = NULL,
            metadata_json = metadata_json || $3::jsonb,
            updated_at = $2
        WHERE id = $1
        """,
        binding_id,
        now,
        metadata,
    )


async def _main_async(args: argparse.Namespace) -> int:
    if args.mode == "apply-file":
        backup_path = _apply_candidate_file(
            args.apply_file,
            args.coredns_overrides_file,
            backup=args.backup,
        )
        print(f"Applied DNS candidate to {args.coredns_overrides_file}")
        if backup_path:
            print(f"Backup: {backup_path}")
        return 0

    if args.mode == "check-tls":
        evidence = _inspect_certificate(args.cert_file, args.hostname)
        print(json.dumps(evidence, ensure_ascii=False, indent=2))
        return 0 if evidence["san_match"] and int(evidence["days_remaining"]) > 0 else 2

    conn = await _connect()
    try:
        if args.mode == "mark-tls-ready":
            evidence = _inspect_certificate(args.cert_file, args.hostname)
            await _mark_tls_ready(conn, binding_id=args.binding_id, actor=args.actor, evidence=evidence)
            print(json.dumps(evidence, ensure_ascii=False, indent=2))
            print(f"Marked binding {args.binding_id} TLS ready.")
            return 0

        rows = await _fetch_pending(conn, limit=args.limit)
        if not rows:
            print("No pending Site Studio DNS outbox rows.")
            return 0
        for row in rows:
            print(f"{row['id']}  {_record(row)}  tls={row['tls_status']} binding={row['binding_status']}")
        if args.write_candidate:
            _write_candidate(rows, args.write_candidate)
            print(f"Wrote DNS candidate: {args.write_candidate}")
        if args.mode == "dry-run":
            return 0
        if not args.yes:
            print("Refusing apply without --yes.", file=sys.stderr)
            return 2
        await _apply_rows(conn, rows, actor=args.actor)
        print(f"Marked {len(rows)} DNS outbox rows as applied.")
        return 0
    finally:
        await conn.close()


def _parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--mode",
        choices=("dry-run", "apply", "apply-file", "check-tls", "mark-tls-ready"),
        default="dry-run",
    )
    parser.add_argument("--limit", type=int, default=100)
    parser.add_argument("--actor", default=os.environ.get("USER", "operator"))
    parser.add_argument("--yes", action="store_true", help="Required for --mode apply.")
    parser.add_argument("--write-candidate", help="Write pending DNS rows to a CoreDNS candidate zone file.")
    parser.add_argument("--apply-file", help="Candidate zone file to install when --mode apply-file is used.")
    parser.add_argument(
        "--coredns-overrides-file",
        default="docker/scripts/internal-sites/coredns/site-studio-custom-domains.db",
        help="Destination CoreDNS override zone file for --mode apply-file.",
    )
    parser.add_argument("--backup", action="store_true", help="Create a timestamped backup before --mode apply-file.")
    parser.add_argument("--cert-file", help="Certificate file for TLS evidence checks.")
    parser.add_argument("--hostname", help="Hostname expected in certificate SAN.")
    parser.add_argument("--binding-id", help="Domain binding id for --mode mark-tls-ready.")
    args = parser.parse_args(argv)
    if args.mode == "apply-file" and not args.apply_file:
        parser.error("--mode apply-file requires --apply-file")
    if args.mode in {"check-tls", "mark-tls-ready"} and (not args.cert_file or not args.hostname):
        parser.error(f"--mode {args.mode} requires --cert-file and --hostname")
    if args.mode == "mark-tls-ready" and not args.binding_id:
        parser.error("--mode mark-tls-ready requires --binding-id")
    return args


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(list(argv or sys.argv[1:]))
    return asyncio.run(_main_async(args))


if __name__ == "__main__":
    raise SystemExit(main())

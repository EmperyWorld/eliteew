#!/usr/bin/env bash
# ---
# EliteEW · Empery World · https://empery.world
# Author: po&T && TZBrand
# ---
# Purpose:
# Materialize role-scoped stack0 env slices from SSOT `.env.stack0.backend`
# for container `env_file:` injection (api / jobs / shared). Compose interpolation
# still uses the full SSOT via `--env-file`.
# Invariants:
# - Keys appear in exactly one role file (failClosed on conflict).
# - Unknown keys default to shared (fail-safe).
# - Never prints secret values.
# Related:
# - documentation/platform/PROD-CORE-CONFIG-PLANE.md
# - docker/stack/stack0_b.yml
# ---
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
ENV_DIR="${ELITEEW_STACK0_ENV_DIR:-${REPO_ROOT}/docker/env_file}"
SSOT="${ENV_DIR}/.env.stack0.backend"
OUT_SHARED="${ENV_DIR}/.env.stack0.shared"
OUT_API="${ENV_DIR}/.env.stack0.api"
OUT_JOBS="${ENV_DIR}/.env.stack0.jobs"

usage() {
  cat <<EOF
Usage: $(basename "$0") [--check]

  Reads ${SSOT} and writes:
    ${OUT_SHARED}
    ${OUT_API}
    ${OUT_JOBS}

  --check  validate classification only (no write)
EOF
}

CHECK_ONLY=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --check) CHECK_ONLY=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "ERROR: unknown arg: $1" >&2; usage >&2; exit 2 ;;
  esac
done

if [[ ! -f "${SSOT}" ]]; then
  echo "ERROR: SSOT missing: ${SSOT}" >&2
  exit 1
fi

# Classification via Python (key names only; values copied verbatim to role files).
python3 - "${SSOT}" "${OUT_SHARED}" "${OUT_API}" "${OUT_JOBS}" "${CHECK_ONLY}" <<'PY'
from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

ssot_path = Path(sys.argv[1])
out_shared = Path(sys.argv[2])
out_api = Path(sys.argv[3])
out_jobs = Path(sys.argv[4])
check_only = sys.argv[5] == "1"

API_PREFIX = (
    "KEYCLOAK_",
    "OIDC_",
    "CORS_",
    "CSP_",
    "HS256_",
    "JWT_",
    "AUTH_",
    "PARITY_",
    "TELEGRAM_",
    "MOBILE_FCM_",
    "MOBILE_TRUSTED_DEVICE_",
)
# Secrets / required keys that every stack0 backend process needs (API mounts
# shared+api; workers/celery mount shared+jobs). Checked before API_PREFIX.
SHARED_FORCE = {
    "KEYCLOAK_CLIENT_SECRET",
    "OIDC_PROVIDER_CLIENT_SECRET",
    "JWT_SECRET_KEY",
}

# Shared by API + jobs: bind enqueue readiness (no SSH private key) + WG server pubkey
# so Celery interface restore can compare expected_pub. SSH private + WG server private
# stay jobs-only (JOBS_PREFIX / remaining MOBILE_PRIVATE_TUNNEL_*).
SHARED_EXACT = {
    "MOBILE_PRIVATE_TUNNEL_EDGE_SYNC_ENABLED",
    "MOBILE_PRIVATE_TUNNEL_EDGE_SSH_HOST",
    "MOBILE_PRIVATE_TUNNEL_EDGE_SSH_USER",
    "MOBILE_PRIVATE_TUNNEL_EDGE_SSH_TIMEOUT_SECONDS",
    "MOBILE_PRIVATE_TUNNEL_INTERFACE",
    "MOBILE_PRIVATE_TUNNEL_PEER_KEEPALIVE_SECONDS",
    "MOBILE_PRIVATE_TUNNEL_EDGE_RECONCILE_INTERVAL_MINUTES",
    "MOBILE_TRUSTED_DEVICE_WG_SERVER_PUBLIC_KEY",
}

# API-only secrets/URLs. Do NOT put UnifiedConfig required-without-default
# keys here — workers/celery load the same UnifiedConfig via shared+jobs only.
# MARKETING_CABINET_ROUTER_MODEL is Field(...) → must stay shared (default class).
API_EXACT = {
    "DESKTOP_CLIENT_BINDING_SPI_TOKEN",
    "PAPERLESS_URL",
    "PAPERLESS_API_TOKEN",
    "MARKETING_CACHE_DB",
}
JOBS_PREFIX = (
    "BROWSER_RENDER_",
    "SCIENCE_STACK_",
    "PLAYWRIGHT_",
    "MOBILE_PRIVATE_TUNNEL_",
)
JOBS_EXACT = {
    "SITE_EDGE_CARRIER_ENABLED",
    "SITE_EDGE_WORKER_HOST",
    "SITE_EDGE_SSH_USER",
    "SITE_EDGE_SSH_KEY_PATH",
    "SITE_EDGE_REMOTE_ROOT",
}
DROP_EXACT = {"N5bmM"}


def classify(key: str) -> str:
    if key in DROP_EXACT:
        return "drop"
    if key in SHARED_FORCE or key in SHARED_EXACT:
        return "shared"
    if key in API_EXACT or any(key.startswith(p) for p in API_PREFIX):
        return "api"
    if key in JOBS_EXACT or any(key.startswith(p) for p in JOBS_PREFIX):
        return "jobs"
    if key.startswith("MOBILE_"):
        return "api"
    return "shared"


KEY_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$")

role_lines: dict[str, list[str]] = defaultdict(list)
role_keys: dict[str, set[str]] = defaultdict(set)
dropped: list[str] = []
conflicts: list[str] = []
seen: dict[str, str] = {}

header = (
    "# Generated by docker/scripts/stack0-env-materialize-roles.sh — do not edit.\n"
    "# SSOT: .env.stack0.backend (compose --env-file still uses SSOT).\n"
)


def iter_env_assignments(text: str):
    """Yield (key, assignment_block) preserving multiline double-quoted values."""
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            i += 1
            continue
        m = KEY_RE.match(stripped)
        if not m:
            i += 1
            continue
        key, val = m.group(1), m.group(2)
        block_lines = [line.rstrip("\n")]
        # Multline: KEY="....  with no closing quote on first line
        if val.startswith('"') and not (val.endswith('"') and len(val) > 1):
            i += 1
            while i < len(lines):
                block_lines.append(lines[i].rstrip("\n"))
                if lines[i].rstrip("\n").endswith('"') or lines[i].strip() == '"':
                    break
                i += 1
        yield key, "\n".join(block_lines)
        i += 1


for key, assignment in iter_env_assignments(
    ssot_path.read_text(encoding="utf-8", errors="replace")
):
    role = classify(key)
    if role == "drop":
        dropped.append(key)
        continue
    if key in seen and seen[key] != role:
        conflicts.append(f"{key}: {seen[key]} vs {role}")
        continue
    if key in seen:
        conflicts.append(f"{key}: duplicate assignment in SSOT")
        continue
    seen[key] = role
    role_keys[role].add(key)
    role_lines[role].append(assignment)

if conflicts:
    print("ERROR: role conflicts:", file=sys.stderr)
    for c in conflicts:
        print(f"  - {c}", file=sys.stderr)
    sys.exit(1)

# FailClosed: no key in more than one role set
overlap_aj = role_keys["api"] & role_keys["jobs"]
overlap_as = role_keys["api"] & role_keys["shared"]
overlap_js = role_keys["jobs"] & role_keys["shared"]
if overlap_aj or overlap_as or overlap_js:
    print("ERROR: overlapping role keys", file=sys.stderr)
    sys.exit(1)

summary = (
    f"stack0 env roles: shared={len(role_keys['shared'])} "
    f"api={len(role_keys['api'])} jobs={len(role_keys['jobs'])} "
    f"dropped={len(dropped)}"
)
print(summary)
if dropped:
    print("dropped keys: " + ", ".join(sorted(dropped)))

if check_only:
    sys.exit(0)

for path, role in (
    (out_shared, "shared"),
    (out_api, "api"),
    (out_jobs, "jobs"),
):
    body = header + f"# role: {role}\n"
    if role_lines[role]:
        body += "\n".join(role_lines[role]) + "\n"
    path.write_text(body, encoding="utf-8")
    path.chmod(0o600)
    print(f"wrote {path.name} ({len(role_keys[role])} keys)")
PY

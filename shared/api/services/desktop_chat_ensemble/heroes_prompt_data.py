def compose_solo_system_prompt(hero_id: str) -> str | None:
    hid = hero_id.strip()
    kernel = HERO_PROMPT_KERNEL.get(hid)
    if not kernel:
        return None
    style = HERO_SOLO_STYLE.get(hid, "")
    parts = [kernel.strip()]
    if style.strip():
        parts.append(style.strip())
    parts.append(HERO_SOLO_AGENCY.strip())
    return "\n\n".join(parts)


def hero_kernel_invariants(hero_id: str) -> tuple[str, ...]:
    """Return compact craft/truth/boundary lines from canonical hero kernel."""
    hid = hero_id.strip()
    kernel = HERO_PROMPT_KERNEL.get(hid)
    if not kernel:
        return ()
    out: list[str] = []
    for raw in kernel.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith(("Зона силы:", "Формат по умолчанию:", "Правда:", "Границы:", "Запрещено")):
            out.append(line)
    return tuple(out)


def get_hero_prompt_version(hero_id: str) -> int:
    return int(HERO_PROMPT_VERSION.get(hero_id.strip(), 1))


def get_hero_dossier_tool_hint(hero_id: str) -> str | None:
    return HERO_DOSSIER_TOOL_HINT.get(hero_id.strip())


def list_hero_catalog_entries() -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for hid, meta in HERO_CATALOG.items():
        row = {"id": hid, "promptVersion": get_hero_prompt_version(hid), **meta}
        out.append(row)
    return out

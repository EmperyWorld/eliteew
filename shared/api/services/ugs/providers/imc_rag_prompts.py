def truncate_prompt_preserve_instructions(prompt: str, max_chars: int) -> tuple[str, bool]:
    """
    Prefer trimming the «Контекст проекта» block; keep methodology/query sections.
    """
    if max_chars <= 0 or len(prompt) <= max_chars:
        return prompt, False
    idx = prompt.find(_CTX_MARKER)
    if idx < 0:
        trimmed = f"{prompt[: max_chars - 50].rstrip()}\n\n… [prompt_truncated]"
        return trimmed, True
    head = prompt[: idx + len(_CTX_MARKER)].rstrip() + "\n\n"
    tail = prompt[idx + len(_CTX_MARKER) :].lstrip()
    budget = max_chars - len(head) - 40
    if budget < 200:
        budget = max_chars - len(_CTX_MARKER) - 80
        head = _CTX_MARKER + "\n\n"
    if budget < 80:
        return f"{head.rstrip()}\n\n… [prompt_truncated]", True
    trimmed_tail = f"{tail[:budget].rstrip()}\n\n… [context_truncated]"
    return head + trimmed_tail, True


def _format_output_sections(sections: Any) -> str | None:
    if isinstance(sections, str) and sections.strip():
        return sections.strip()
    if isinstance(sections, list):
        lines = [str(s).strip() for s in sections if str(s).strip()]
        if lines:
            return "\n".join(f"- {line}" for line in lines)
    return None


def imc_output_sections_list(raw: Any) -> list[str]:
    """Список непустых заголовков разделов для оркестрации (только list[str] в v1)."""
    if isinstance(raw, list):
        return [str(s).strip() for s in raw if str(s).strip()]
    return []



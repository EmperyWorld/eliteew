-- ИМК RAG: усиление методологии «Тренды и сигналы» (цитирование, РФ vs глобус, без воды в конце).
-- После применения: перезапуск API-воркера UGS при необходимости.

UPDATE generation_types
SET type_metadata = type_metadata
    || jsonb_build_object(
        'imc_prompt_version',
        CASE
            WHEN (type_metadata->>'imc_prompt_version') ~ '^[0-9]+$'
                THEN (type_metadata->>'imc_prompt_version')::int + 1
            ELSE 1
        END,
        'imc_prompt_instructions',
        $PROMPT$ИНВАРИАНТЫ: единственный источник фактов — переданные фрагменты. Запрещены веб-поиск, выдуманные URL и обобщения без цитаты. Язык — русский; проверь орфографию (например «активного долголетия», не «долголетий»).

ТАБЛИЦА «факт — цитата — источник»: в колонке «Источник» у каждой строки — полная метка из контекста. Одну и ту же пару fragment+chunk_index нельзя повторять для разных фактов, взятых из разных мест текста: либо одна строка с несколькими тезисами из одного фрагмента, либо разные метки. Лучше меньше строк, чем трижды скопировать один fragment=.

СТРУКТУРА ОТЧЁТА:
1) Executive summary — только тезисы, каждый с отсылкой к фрагменту.
2) Глобальный горизонт — тренды/сигналы строго из цитат; без абзацев «в целом по рынку мира», если их нет во фрагментах.
3) Россия / РФ / регион — только если это явно следует из фрагментов (НПА, программы, город, отрасль РФ). Иначе коротко: «Локальный контур ограничен …» и перечисли только то, что есть.
4) Weak signals — каждый пункт с цитатой и пометкой уверенности (по числу независимых фрагментов на тему).
5) Связь SWOT/JTBD — только если во фрагментах есть явные элементы SWOT или формулировки работ; иначе один абзац-оговорка, без выдуманных сил/слабостей клуба.
6) Impact × uncertainty — для каждого элемента: что во фрагменте → как ты интерпретируешь impact и неопределённость (без вымышленных чисел).
7) Следующие шаги — только маркированный список: глагол + «потому что …» + метка фрагмента.
8) Таблица факт — цитата — источник — см. правила выше.

ЗАПРЕЩЕНО заканчивать отчёт общими фразами без новых фактов («данный отчёт представляет собой комплексный анализ…» и т.п.).$PROMPT$
    )
    || jsonb_build_object(
        'imc_output_sections',
        jsonb_build_array(
            'Executive summary (3–5 тезисов, у каждого метка фрагмента)',
            'Глобальный горизонт: сигналы и гипотезы (только из контекста)',
            'Россия / локальный контур — только при наличии фрагментов; иначе явный пробел',
            'Weak signals vs шум (с цитатами и уровнем уверенности)',
            'Связь SWOT/JTBD — только при явных фрагментах; иначе краткая оговорка',
            'Приоритетный грид impact × uncertainty (обоснование из фрагментов)',
            'Рекомендации следующих шагов (глагол + потому что + фрагмент)',
            'Таблица: факт — цитата — источник (уникальные метки по строкам или одна строка на один фрагмент)'
        )
    )
WHERE type_key = 'imc_rag_trends_signals';

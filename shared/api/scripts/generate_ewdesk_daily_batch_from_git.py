def _date_range(start: date, end: date) -> list[date]:
    out: list[date] = []
    cur = start
    while cur <= end:
        out.append(cur)
        cur += timedelta(days=1)
    return out


def _render_draft(posts: list[dict[str, str]]) -> str:
    lines = [
        "# EWDesk — черновики постов (14 июня — 17 августа 2026), v2",
        "",
        "Сгенерировано из git-истории; user-facing, без операторского жаргона.",
        "Публикация: `publish_ewdesk_news_batch_direct.py --no-rewrite`.",
        "",
    ]
    for i, p in enumerate(posts):
        if i:
            lines.append("---")
            lines.append("")
        lines.extend(
            [
                f"## `{p['id']}`",
                "",
                f"**Заголовок:** {p['title']}",
                "",
                "**Тело:**",
                "",
                p["body"],
                "",
            ]
        )
        if p.get("links"):
            lines.append(p["links"].strip())
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _build_posts(start: date, end: date) -> list[dict[str, str]]:
    posts: list[dict[str, str]] = []
    for d in _date_range(start, end):
        ds = d.isoformat()
        if ds not in _DAY_OVERRIDES:
            msg = f"missing override for {ds}"
            raise KeyError(msg)
        suffix, title, body, clip, links = _DAY_OVERRIDES[ds]
        slug = f"{ds}-{suffix}"
        posts.append(
            {
                "id": slug,
                "title": title,
                "body": body,
                "clip_prompt": clip,
                "links": links,
            }
        )
    return posts


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--start", default="2026-06-14")
    ap.add_argument("--end", default="2026-08-17")
    ap.add_argument(
        "--draft-out",
        type=Path,
        default=_REPO / "documentation/product/desktop/EWDESK-POSTS-BATCH-DRAFT-2026-06-14-08-17.md",
    )
    ap.add_argument(
        "--manifest-out",
        type=Path,
        default=_REPO / "host/comfyui/ewdesk_batch_manifest_20260614_0817.json",
    )
    args = ap.parse_args()
    start = date.fromisoformat(args.start)
    end = date.fromisoformat(args.end)
    posts = _build_posts(start, end)
    draft = _render_draft(posts)
    args.draft_out.parent.mkdir(parents=True, exist_ok=True)
    args.draft_out.write_text(draft, encoding="utf-8")
    manifest = {"posts": [{"id": p["id"], "clip_prompt": p["clip_prompt"]} for p in posts]}
    args.manifest_out.parent.mkdir(parents=True, exist_ok=True)
    args.manifest_out.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(posts)} posts -> {args.draft_out}")
    print(f"manifest -> {args.manifest_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

from __future__ import annotations

from types import SimpleNamespace

import pytest

from api.services.site_studio_ai_service import SiteStudioAIError, SiteStudioAIService, _extract_json_object


class _DummyDbSession:
    pass


def test_extract_json_object_handles_fence_comments_and_trailing_commas() -> None:
    raw = """```json
{
  // generated by model
  "title": "Pack",
  "summary": "ok",
  "blocks": [
    {"page": "home", "section": "hero", "key": "headline_1", "value": "A"},
  ],
}
```"""
    parsed = _extract_json_object(raw)
    assert parsed["title"] == "Pack"
    assert isinstance(parsed.get("blocks"), list)


def test_extract_json_object_accepts_single_object_list_root() -> None:
    raw = '[{"brief":"Тест","siteBlueprint":{"brandCore":"Lexus","audience":["VIP"]}}]'
    parsed = _extract_json_object(raw)
    assert parsed["brief"] == "Тест"
    assert parsed["siteBlueprint"]["brandCore"] == "Lexus"


def test_extract_json_object_merges_multiple_object_list_items() -> None:
    raw = '[{"brief":"Тест"},{"siteBlueprint":{"brandCore":"Lexus"}}]'
    parsed = _extract_json_object(raw)
    assert parsed["brief"] == "Тест"
    assert parsed["siteBlueprint"]["brandCore"] == "Lexus"


@pytest.mark.unit
@pytest.mark.asyncio
async def test_complete_json_prompt_repair_pass_on_invalid_json(monkeypatch: pytest.MonkeyPatch) -> None:
    service = SiteStudioAIService(_DummyDbSession())  # type: ignore[arg-type]
    prompts: list[str] = []

    async def _fake_complete_text_prompt(**kwargs: object) -> str:
        prompt = str(kwargs.get("prompt") or "")
        prompts.append(prompt)
        if len(prompts) == 1:
            # missing closing brace -> unrecoverable for parser without repair call
            return '{"title":"Pack","blocks":[{"page":"home"}]'
        return '{"title":"Pack","blocks":[{"page":"home"}]}'

    monkeypatch.setattr(service, "_complete_text_prompt", _fake_complete_text_prompt)

    parsed = await service._complete_json_prompt(
        prompt="Return JSON",
        context="ctx",
        user_id="user-1",
        temperature=0.4,
        max_tokens=1000,
    )

    assert parsed["title"] == "Pack"
    assert len(prompts) == 2
    assert "Исправь синтаксис JSON-ответа" in prompts[1]


@pytest.mark.unit
@pytest.mark.asyncio
async def test_complete_json_prompt_raises_when_repair_still_invalid(monkeypatch: pytest.MonkeyPatch) -> None:
    service = SiteStudioAIService(_DummyDbSession())  # type: ignore[arg-type]

    async def _always_invalid(**_: object) -> str:
        return '{"title":"Pack","blocks":['

    monkeypatch.setattr(service, "_complete_text_prompt", _always_invalid)


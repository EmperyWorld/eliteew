#!/usr/bin/env node
/**
 * Scans shared/web/frontend/src for /api* string literals and baseURL hints.
 * Usage:
 *   node scripts/api-inventory.mjs
 *   node scripts/api-inventory.mjs --write
 *     (writes documentation/api/fe-be-api-inventory.snapshot.md at monorepo root)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SRC_ROOT = path.join(__dirname, '..', 'src');

const API_STRING_RE = /(["'`])(\/api(?:\/[\w\-./{}$:?&=*%!@#+~[\]]*)?)\1/g;
const BASEURL_RE = /baseURL\s*:\s*(["'`])([^"'`]+)\1/g;

function* walkTsFiles(dir) {
	const entries = fs.readdirSync(dir, { withFileTypes: true });
	for (const ent of entries) {
		const full = path.join(dir, ent.name);
		if (ent.isDirectory()) {
			if (
				ent.name === 'node_modules' ||
				ent.name === 'dist' ||
				ent.name === 'generated'
			) {
				continue;
			}
			yield* walkTsFiles(full);
		} else if (/\.(ts|tsx)$/.test(ent.name)) {
			yield full;
		}
	}
}

function collectInventory() {
	/** @type {Map<string, { apis: Set<string>, baseUrls: Set<string> }>} */
	const byFile = new Map();

	for (const file of walkTsFiles(SRC_ROOT)) {
		const rel = path.relative(path.join(__dirname, '..'), file).replace(/\\/g, '/');
		const text = fs.readFileSync(file, 'utf8');
		const apis = new Set();
		const baseUrls = new Set();

		let m;
		API_STRING_RE.lastIndex = 0;
		while ((m = API_STRING_RE.exec(text)) !== null) {
			const s = m[2];
			if (s.length < 5) continue;
			if (s.includes('${')) continue;
			if (s.includes('`') && m[1] === '`') continue;
			apis.add(s);
		}

		BASEURL_RE.lastIndex = 0;
		while ((m = BASEURL_RE.exec(text)) !== null) {
			const u = m[2];
			if (u.includes('/api')) baseUrls.add(u);
		}

		if (apis.size || baseUrls.size) {
			byFile.set(rel, { apis, baseUrls });
		}
	}

	return byFile;
}

function toMarkdown(byFile) {
	const lines = [
		'# FE/BE API inventory snapshot',
		'',
		'Auto-generated by `pnpm run api:inventory` (do not hand-edit).',
		'',
	];

	const sorted = [...byFile.entries()].sort((a, b) => a[0].localeCompare(b[0]));
	for (const [rel, { apis, baseUrls }] of sorted) {
		lines.push(`## \`${rel}\``);
		if (apis.size) {
			lines.push('### Paths');
			for (const p of [...apis].sort()) {
				lines.push(`- \`${p}\``);
			}
		}
		if (baseUrls.size) {
			lines.push('### baseURL');
			for (const b of [...baseUrls].sort()) {
				lines.push(`- \`${b}\``);
			}
		}
		lines.push('');
	}
	return lines.join('\n');
}

const byFile = collectInventory();
const md = toMarkdown(byFile);

const REPO_ROOT = path.resolve(__dirname, '..', '..', '..', '..');
const DEFAULT_SNAPSHOT = path.join(
	REPO_ROOT,
	'documentation',
	'api',
	'fe-be-api-inventory.snapshot.md'
);

if (process.argv.includes('--write')) {
	const out = DEFAULT_SNAPSHOT;
	fs.mkdirSync(path.dirname(out), { recursive: true });
	fs.writeFileSync(out, md, 'utf8');
	console.log('Wrote', out);
} else {
	console.log(md);
}

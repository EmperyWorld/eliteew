	'blueprint_only' as const;

export const DESKTOP_ENSEMBLE_ROUTING_MODE_ORDER = [
	DESKTOP_ENSEMBLE_ROUTING_AUTO,
	DESKTOP_ENSEMBLE_ROUTING_SEMI,
	DESKTOP_ENSEMBLE_ROUTING_CHAT_ONLY,
	DESKTOP_ENSEMBLE_ROUTING_BLUEPRINT_ONLY,
] as const;

export type DesktopEnsembleRoutingMode =
	(typeof DESKTOP_ENSEMBLE_ROUTING_MODE_ORDER)[number];

export function resolveDesktopEnsembleRoutingMode(
	settings: Record<string, unknown> | undefined | null
): DesktopEnsembleRoutingMode {
	const raw = settings?.desktop_ensemble_routing_mode;
	if (typeof raw === 'string') {
		const s = raw.trim();
		for (const m of DESKTOP_ENSEMBLE_ROUTING_MODE_ORDER) {
			if (m === s) {
				return m;
			}
		}
	}
	return DESKTOP_ENSEMBLE_ROUTING_AUTO;
}


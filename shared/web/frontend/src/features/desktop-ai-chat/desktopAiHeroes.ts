/** Full catalog: assistants, collective souls, then IT department (picker sections). */
export const DESKTOP_AI_HEROES: readonly DesktopAiHero[] = [
	...DESKTOP_AI_ASSISTANT_HEROES,
	...DESKTOP_AI_COLLECTIVE_SOULS_HEROES,
	...DESKTOP_AI_IT_DEPT_HEROES,
];

export function desktopAiHeroCohort(
	hero: DesktopAiHero | undefined
): DesktopAiHeroCohort {
	if (hero?.cohort === 'it_dept') {
		return 'it_dept';
	}
	if (hero?.cohort === 'collective_souls') {
		return 'collective_souls';
	}
	return 'assistants';
}

export function desktopAiHeroesByCohort(
	cohort: DesktopAiHeroCohort
): readonly DesktopAiHero[] {
	return DESKTOP_AI_HEROES.filter((h) => desktopAiHeroCohort(h) === cohort);
}

export function getDesktopAiHero(
	id: string | undefined
): DesktopAiHero | undefined {
	if (!id) return undefined;
	return DESKTOP_AI_HEROES.find((h) => h.id === id);
}

/** Голос TTS для соло-чата; без героя — нейтральный женский (как раньше для всех). */
export function desktopHeroSileroVoice(
	heroId: string | null | undefined
): DesktopAiSileroVoiceId {
	if (!heroId) {
		return DEFAULT_DESKTOP_AI_SILERO_VOICE;
	}
	return (
		getDesktopAiHero(heroId)?.sileroVoice ?? DEFAULT_DESKTOP_AI_SILERO_VOICE
	);
}

export function heroAvatarPublicPath(
	id: string | null | undefined
): string | null {
	const h = getDesktopAiHero(id ?? undefined);
	return h?.avatarPublicPath ?? null;
}

export function heroShortLabelFromSettings(
	settings: Record<string, unknown> | undefined
): string | null {
	const raw = settings?.desktop_hero_id;
	if (typeof raw !== 'string') return null;
	const h = getDesktopAiHero(raw);
	return h?.shortLabel ?? null;
}

export function isDesktopEnsembleChat(
	settings: Record<string, unknown> | undefined
): boolean {
	return settings?.desktop_chat_mode === DESKTOP_CHAT_MODE_ENSEMBLE;
}

/** Подпись в списке чатов / шапке: соло-герой или «Команда». */
export function desktopChatSideLabel(
	settings: Record<string, unknown> | undefined
): string | null {
	if (isDesktopEnsembleChat(settings)) {
		return 'Команда';
	}
	return heroShortLabelFromSettings(settings);
}

/**
 * Персонажи в ростере ensemble (согласовано с `get_ensemble_roster` на API).
 * Для пустого/битого payload возвращает весь каталог — как fallback бэкенда.
 */
export function desktopEnsembleRosterHeroes(
	settings: Record<string, unknown> | undefined
): readonly DesktopAiHero[] {
	if (!settings || !isDesktopEnsembleChat(settings)) {
		return [];
	}
	if (settings.desktop_ensemble_all === true) {
		return DESKTOP_AI_ASSISTANT_HEROES.slice(0, DESKTOP_ENSEMBLE_MAX_ROSTER);
	}
	const raw = settings.desktop_ensemble_ids;
	if (Array.isArray(raw)) {
		const seen = new Set<string>();
		const out: DesktopAiHero[] = [];
		for (const x of raw) {
			if (typeof x !== 'string') continue;
			const h = getDesktopAiHero(x.trim());
			if (!h || seen.has(h.id)) continue;
			seen.add(h.id);
			out.push(h);
		}
		if (out.length > 0) {
			return out.slice(0, DESKTOP_ENSEMBLE_MAX_ROSTER);
		}
	}
	return DESKTOP_AI_ASSISTANT_HEROES.slice(0, DESKTOP_ENSEMBLE_MAX_ROSTER);
}
